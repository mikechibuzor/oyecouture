import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { products } from './product-data.js'

const CHECK_MODE = '--check'
const KOBO_PER_NAIRA = 100
const PRODUCT_SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/
const VALID_PRODUCT_SECTIONS = new Set([
  'suits',
  'trad',
  'casuals-men',
  'casuals-women',
])
const VALID_PRODUCT_TAGS = new Set(['', 'New', 'Bespoke'])
const generatorDirectory = dirname(fileURLToPath(import.meta.url))
const upMigrationPath = resolve(
  generatorDirectory,
  '../api/migrations/000002_seed_products.up.sql',
)
const downMigrationPath = resolve(
  generatorDirectory,
  '../api/migrations/000002_seed_products.down.sql',
)

// Assert that a catalogue field is a populated string.
function assertNonEmptyString(productSlug, fieldName, fieldValue) {
  if (typeof fieldValue !== 'string' || fieldValue.trim() === '') {
    throw new TypeError(`${productSlug}.${fieldName} must be a non-empty string`)
  }
}

// Validate the canonical catalogue before any SQL is generated from it.
function validateCatalogue(catalogueProducts) {
  if (!Array.isArray(catalogueProducts) || catalogueProducts.length === 0) {
    throw new TypeError('products must be a non-empty array')
  }

  // Track slugs while walking every product and validating its database mapping.
  const seenProductSlugs = new Set()
  for (const product of catalogueProducts) {
    if (product === null || typeof product !== 'object' || Array.isArray(product)) {
      throw new TypeError('every product must be an object')
    }

    assertNonEmptyString('product', 'id', product.id)
    const productSlug = product.id

    if (!PRODUCT_SLUG_PATTERN.test(productSlug)) {
      throw new TypeError(`${productSlug}.id must be a lowercase URL-safe slug`)
    }
    if (seenProductSlugs.has(productSlug)) {
      throw new TypeError(`duplicate product slug: ${productSlug}`)
    }
    seenProductSlugs.add(productSlug)

    assertNonEmptyString(productSlug, 'name', product.name)
    assertNonEmptyString(productSlug, 'cat', product.cat)
    assertNonEmptyString(productSlug, 'section', product.section)
    assertNonEmptyString(productSlug, 'description', product.description)

    if (!VALID_PRODUCT_SECTIONS.has(product.section)) {
      throw new TypeError(`${productSlug}.section is not supported`)
    }
    if (typeof product.tag !== 'string' || !VALID_PRODUCT_TAGS.has(product.tag)) {
      throw new TypeError(`${productSlug}.tag is not supported`)
    }
    if (!Number.isSafeInteger(product.price) || product.price <= 0) {
      throw new TypeError(`${productSlug}.price must be a positive integer in naira`)
    }
    if (!Number.isSafeInteger(product.price * KOBO_PER_NAIRA)) {
      throw new RangeError(`${productSlug}.price exceeds the safe kobo range`)
    }
    if (typeof product.hasSizes !== 'boolean') {
      throw new TypeError(`${productSlug}.hasSizes must be a boolean`)
    }
  }
}

// Escape a text value for a PostgreSQL single-quoted literal.
function formatSQLText(value) {
  return `'${value.replaceAll("'", "''")}'`
}

// Map one canonical catalogue item into a deterministic SQL values tuple.
function formatProductTuple(product, sortOrder) {
  const priceKobo = product.price * KOBO_PER_NAIRA
  const hasSizes = product.hasSizes ? 'TRUE' : 'FALSE'

  return [
    '  (',
    `    ${formatSQLText(product.id)},`,
    `    ${formatSQLText(product.name)},`,
    `    ${formatSQLText(product.section)},`,
    `    ${formatSQLText(product.cat)},`,
    `    ${priceKobo},`,
    `    ${formatSQLText(product.description)},`,
    `    ${formatSQLText(product.tag)},`,
    `    ${hasSizes},`,
    `    ${sortOrder}`,
    '  )',
  ].join('\n')
}

// Build the forward seed migration from the validated canonical order.
function buildUpMigration(catalogueProducts) {
  const productTuples = []
  for (const [sortOrder, product] of catalogueProducts.entries()) {
    productTuples.push(formatProductTuple(product, sortOrder))
  }

  return [
    '-- Code generated by catalogue/generate-product-seed.mjs. DO NOT EDIT.',
    'INSERT INTO products (',
    '    slug,',
    '    name,',
    '    section,',
    '    category,',
    '    price_kobo,',
    '    description,',
    '    tag,',
    '    has_sizes,',
    '    sort_order',
    ')',
    'VALUES',
    productTuples.join(',\n'),
    'ON CONFLICT (slug) DO UPDATE SET',
    '    name = EXCLUDED.name,',
    '    section = EXCLUDED.section,',
    '    category = EXCLUDED.category,',
    '    price_kobo = EXCLUDED.price_kobo,',
    '    description = EXCLUDED.description,',
    '    tag = EXCLUDED.tag,',
    '    has_sizes = EXCLUDED.has_sizes,',
    '    sort_order = EXCLUDED.sort_order;',
    '',
  ].join('\n')
}

// Build the reverse seed migration for the exact canonical product slugs.
function buildDownMigration(catalogueProducts) {
  const productSlugs = []
  for (const product of catalogueProducts) {
    productSlugs.push(`    ${formatSQLText(product.id)}`)
  }

  return [
    '-- Code generated by catalogue/generate-product-seed.mjs. DO NOT EDIT.',
    'DELETE FROM products',
    'WHERE slug IN (',
    productSlugs.join(',\n'),
    ');',
    '',
  ].join('\n')
}

// Write a generated migration only when its deterministic content changes.
async function writeMigration(migrationPath, migrationContent) {
  let existingContent = null
  try {
    existingContent = await readFile(migrationPath, 'utf8')
  } catch (error) {
    if (error.code !== 'ENOENT') {
      throw error
    }
  }

  if (existingContent !== migrationContent) {
    await writeFile(migrationPath, migrationContent, 'utf8')
  }
}

// Verify that a committed migration still matches the canonical catalogue.
async function checkMigration(migrationPath, migrationContent) {
  const existingContent = await readFile(migrationPath, 'utf8')
  if (existingContent !== migrationContent) {
    throw new Error(`generated migration is stale: ${migrationPath}`)
  }
}

// Validate catalogue data, generate both directions, and write or check them.
async function main() {
  // Refuse to generate SQL from incomplete, duplicated, or invalid source data.
  validateCatalogue(products)

  // Build deterministic up and down migrations from the same validated products.
  const upMigration = buildUpMigration(products)
  const downMigration = buildDownMigration(products)
  const shouldCheckOnly = process.argv.includes(CHECK_MODE)

  // Either verify committed output or refresh it for an intentional catalogue change.
  if (shouldCheckOnly) {
    await checkMigration(upMigrationPath, upMigration)
    await checkMigration(downMigrationPath, downMigration)
    return
  }

  await writeMigration(upMigrationPath, upMigration)
  await writeMigration(downMigrationPath, downMigration)
}

await main()
