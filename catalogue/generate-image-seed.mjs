// Generates the product_images seed migration from the curated slug -> file map
// in web/constants/products.ts, verifying every referenced file exists on disk.
//
// Storage keys are stored bare (e.g. "oye-p-monarch.webp") so the storage host is
// swappable via R2_PUBLIC_BASE alone: "/images/catalogue" today, an R2 bucket URL
// later, with no code or data change.
//
//   node generate-image-seed.mjs          # write the migration
//   node generate-image-seed.mjs --check  # verify the migration is up to date
import { access, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const CHECK_MODE = '--check'
const MAXIMUM_POSITION = 3
const generatorDirectory = dirname(fileURLToPath(import.meta.url))
const constantsPath = resolve(generatorDirectory, '../web/constants/products.ts')
const imageDirectory = resolve(generatorDirectory, '../web/public/images/catalogue')
const upMigrationPath = resolve(
  generatorDirectory,
  '../api/migrations/000003_seed_product_images.up.sql',
)
const downMigrationPath = resolve(
  generatorDirectory,
  '../api/migrations/000003_seed_product_images.down.sql',
)

// Extracts the slug -> image path map from the frontend constants file.
const readFallbackImageMap = async () => {
  const source = await readFile(constantsPath, 'utf8')
  const blockMatch = source.match(
    /export const PRODUCT_FALLBACK_IMAGES[^=]*=\s*\{([\s\S]*?)\n\}/,
  )
  if (!blockMatch) {
    throw new Error('PRODUCT_FALLBACK_IMAGES not found in web/constants/products.ts')
  }

  const imageMap = new Map()
  const entryPattern = /(\w+):\s*\[([^\]]*)\]/g
  let entryMatch
  while ((entryMatch = entryPattern.exec(blockMatch[1])) !== null) {
    const slug = entryMatch[1]
    const paths = [...entryMatch[2].matchAll(/'([^']+)'/g)].map((m) => m[1])
    if (paths.length > 0) {
      imageMap.set(slug, paths)
    }
  }

  return imageMap
}

// Converts a public image path into a bare, storage-portable object key.
const toStorageKey = (imagePath) => imagePath.replace(/^.*\//, '')

// Fails loudly if a referenced image is missing, so the seed can never point to nothing.
const assertImageExists = async (storageKey) => {
  try {
    await access(resolve(imageDirectory, storageKey))
  } catch {
    throw new Error(`referenced image is missing on disk: ${storageKey}`)
  }
}

const buildMigrations = async () => {
  const imageMap = await readFallbackImageMap()
  const rows = []

  for (const [slug, imagePaths] of [...imageMap].sort(([a], [b]) => a.localeCompare(b))) {
    if (imagePaths.length > MAXIMUM_POSITION) {
      throw new Error(`${slug} has ${imagePaths.length} images; the schema allows ${MAXIMUM_POSITION}`)
    }

    for (const [index, imagePath] of imagePaths.entries()) {
      const storageKey = toStorageKey(imagePath)
      await assertImageExists(storageKey)
      rows.push({ slug, storageKey, position: index + 1 })
    }
  }

  if (rows.length === 0) {
    throw new Error('no product images resolved; refusing to write an empty seed')
  }

  const header = '-- Code generated by catalogue/generate-image-seed.mjs. DO NOT EDIT.\n'
  const values = rows
    .map((row) => `    ('${row.slug}', '${row.storageKey}', ${row.position})`)
    .join(',\n')

  const upMigration = `${header}-- Storage keys are bare filenames; R2_PUBLIC_BASE decides where they resolve.
INSERT INTO product_images (product_id, r2_key, position)
SELECT
    product.id,
    seed.r2_key,
    seed.position
FROM (
  VALUES
${values}
) AS seed (slug, r2_key, position)
JOIN products AS product ON product.slug = seed.slug
ON CONFLICT (r2_key) DO NOTHING;
`

  const keyList = rows.map((row) => `    '${row.storageKey}'`).join(',\n')
  const downMigration = `${header}DELETE FROM product_images
WHERE r2_key IN (
${keyList}
);
`

  return { upMigration, downMigration, rowCount: rows.length, productCount: imageMap.size }
}

const main = async () => {
  const { upMigration, downMigration, rowCount, productCount } = await buildMigrations()

  if (process.argv.includes(CHECK_MODE)) {
    const [currentUp, currentDown] = await Promise.all([
      readFile(upMigrationPath, 'utf8').catch(() => ''),
      readFile(downMigrationPath, 'utf8').catch(() => ''),
    ])

    if (currentUp !== upMigration || currentDown !== downMigration) {
      console.error('product image seed is out of date; re-run without --check')
      process.exit(1)
    }

    console.log(`product image seed is current (${rowCount} images across ${productCount} products)`)
    return
  }

  await writeFile(upMigrationPath, upMigration, 'utf8')
  await writeFile(downMigrationPath, downMigration, 'utf8')
  console.log(`wrote ${rowCount} image rows across ${productCount} products`)
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
